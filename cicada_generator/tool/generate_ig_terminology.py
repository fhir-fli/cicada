#!/usr/bin/env python3
"""Publish the engine's ConceptMap in the IG, and derive the IG's code value sets from it.

WHY. Until 2026-10-18 the IG published two FSH ConceptMaps generated from the
hand-typed crosswalk (cm_icd10_to_cdsi.fsh said asplenia D73.0 was
'equivalent' to 018, hepatitis A immunity) and four hand-kept value sets.
The engine now reads one graded ConceptMap
(cicada_generator/lib/crosswalk/ConceptMap-cdsi-observations.json); the IG
publishes that same file, and each value set lists exactly the codes in it
that assert an observation, so the two cannot drift.

Writes, each flushed:
  cicada_ig/input/resources/ConceptMap-cdsi-observations.json   (a copy)
  cicada_ig/input/fsh/vs_vaccine_condition_codes_{icd10,loinc,rxnorm,cpt}.fsh
    (a system with no asserting code gets no value set)

Usage: generate_ig_terminology.py <ConceptMap.json> <cicada_ig dir>
"""
import json
import shutil
import sys
from pathlib import Path

ASSERTS = {'equivalent', 'equal', 'wider', 'subsumes'}

VALUE_SETS = {
    'http://hl7.org/fhir/sid/icd-10-cm': (
        'vs_vaccine_condition_codes_icd10.fsh', 'VaccineConditionCodesIcd10',
        'vaccine-condition-codes-icd10', 'Vaccine Condition Codes (ICD-10-CM)',
        'ICD-10-CM codes that assert a CDSi observation in ConceptMap cdsi-observations.'),
    'http://loinc.org': (
        'vs_vaccine_condition_codes_loinc.fsh', 'VaccineLabEvidenceOfImmunityLoinc',
        'vaccine-lab-evidence-of-immunity-loinc', 'Lab Evidence of Immunity (LOINC)',
        'LOINC antibody tests that are laboratory evidence of immunity in ConceptMap '
        'cdsi-observations, only with a positive result. IgM, cerebrospinal fluid and '
        'avidity codes are deliberately excluded.'),
    'http://www.nlm.nih.gov/research/umls/rxnorm': (
        'vs_vaccine_condition_codes_rxnorm.fsh', 'VaccineMedicationCodesRxnorm',
        'vaccine-medication-codes-rxnorm', 'Immunization-Relevant Medications (RxNorm)',
        'RxNorm codes that assert a CDSi observation in ConceptMap cdsi-observations.'),
    'http://www.ama-assn.org/go/cpt': (
        'vs_vaccine_condition_codes_cpt.fsh', 'ImmunizationProceduresCpt',
        'immunization-procedures-cpt', 'Immunization-Relevant Procedures (CPT)',
        'CPT codes that assert a CDSi observation in ConceptMap cdsi-observations.'),
}


def fsh_string(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def main(map_path, ig_dir):
    ig = Path(ig_dir)
    concept_map = json.load(open(map_path, encoding='utf-8'))
    dest = ig / 'input' / 'resources' / 'ConceptMap-cdsi-observations.json'
    shutil.copyfile(map_path, dest)
    print(f'copied -> {dest}', flush=True)
    groups = {g['source']: g for g in concept_map['group']}
    for system, (fname, name, vs_id, title, description) in VALUE_SETS.items():
        group = groups.get(system, {'element': []})
        codes = [(e['code'], e.get('display', ''))
                 for e in group['element']
                 if any(t['equivalence'] in ASSERTS for t in e.get('target', []))]
        out = ig / 'input' / 'fsh' / fname
        if not codes:
            # ValueSet.compose.include is 1..* (R4B StructureDefinition-ValueSet.json,
            # read 2026-10-18): a value set with nothing to
            # include is not published.
            out.unlink(missing_ok=True)
            print(f'0 codes for {system}: {out} removed', flush=True)
            continue
        with open(out, 'w', encoding='utf-8') as f:
            f.write('// GENERATED by cicada_generator/tool/generate_ig_terminology.py from\n'
                    '// cicada_generator/lib/crosswalk/ConceptMap-cdsi-observations.json -- do not edit.\n'
                    '// Earlier hand-kept versions and why they were replaced: git log on this file.\n')
            f.write(f'ValueSet: {name}\nId: {vs_id}\nTitle: "{title}"\n'
                    f'Description: "{fsh_string(description)}"\n'
                    '* ^experimental = false\n* ^status = #active\n')
            for code, display in codes:
                f.write(f'* include {system}#{code} "{fsh_string(display)}"\n')
                f.flush()
        print(f'{len(codes)} codes -> {out}', flush=True)


if __name__ == '__main__':
    main(*sys.argv[1:3])
